"""Provenance tagging for data, parameters, and simulation outputs.

Strictly distinguishes ASSUMED starting assumptions, SIMULATED outputs,
and MEASURED physical telemetry.
"""

from enum import Enum
from typing import Any, Generic, Optional, TypeVar
from pydantic import BaseModel, Field

T = TypeVar("T")


class DataProvenance(str, Enum):
    """Categorization of data source validity."""
    ASSUMED = "ASSUMED"       # Starting engineering assumption, unvalidated
    SIMULATED = "SIMULATED"   # Generated by software simulation model
    MEASURED = "MEASURED"     # Real physical telemetry or benchmark observation


class ProvenanceValue(BaseModel, Generic[T]):
    """Container pairing a datum with its verified source provenance."""
    value: Any
    provenance: DataProvenance = Field(
        ...,
        description="Origin class of this data point (ASSUMED, SIMULATED, MEASURED)"
    )
    notes: Optional[str] = Field(
        default=None,
        description="Clarifying notes, parameter source, or simulation environment info"
    )
